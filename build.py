#!/usr/bin/env python3
"""Build agent-rules source into per-agent artifacts.

python3 stdlib only. No PyYAML: frontmatter is authored by us and restricted to a
documented subset (scalars, block scalars, and simple lists).

    python3 build.py                # build dist/
    python3 build.py --lint-only    # validate without writing
    python3 build.py --verify-vendor # check vendor/books against the lockfile
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
VENDOR = ROOT / "vendor"
DIST = ROOT / "dist"
VERSION = (ROOT / "VERSION").read_text(encoding="utf-8").strip() if (ROOT / "VERSION").exists() else "0.0.0"

# Byte budgets. Claude can afford the full core; Codex shares a 32 KiB total doc
# budget with every project AGENTS.md, so its artifact is capped much harder.
# Raised from 16 KiB when the design-defaults layer was added. Every byte here is
# paid on every turn of every task, so treat an increase as a decision, not a fix:
# prefer moving content into a skill.
BUDGET_CLAUDE_CORE = 24576
# Codex shares one budget across global + every project AGENTS.md. Default is 32 KiB;
# install raises it to 64 KiB. 16 KiB here still leaves 16 KiB for project docs even
# if the config patch never ran.
BUDGET_CODEX = 18432
# Scoped rules load only on a path match, so this budget is far less precious than
# core's — raised when the AI/vector schema rules were added.
BUDGET_SCOPED_TOTAL = 24576
SKILL_DESC_MAX = 1536  # description + when_to_use, combined, per Claude's truncation

PREFIX_TOKEN = "@AIRULES_PREFIX@"  # substituted with the install path at install time

GENERATED = "<!-- GENERATED by build.py — DO NOT EDIT — edit src/ and rebuild. agent-rules {v} -->"

# Secrets / PII / stale-context scan. The repo is public.
FORBIDDEN = [
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+"), "email address"),
    (re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b"), "IP address"),
    (re.compile(r"\b20\d{2}-\d{2}-\d{2}\b"), "hardcoded absolute date"),
    (re.compile(r"\b(gh[pousr]_[A-Za-z0-9]{16,}|sk-[A-Za-z0-9]{16,}|AKIA[0-9A-Z]{16})"), "credential"),
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"), "private key"),
]
# Placeholders that look like the real thing but are not.
ALLOWED_SUBSTRINGS = ("<user>@<server-ip>", "user@host", "0.0.0.0", "127.0.0.1", "<dockerhub-user>")


class BuildError(Exception):
    pass


# ---------------------------------------------------------------- frontmatter


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Return (frontmatter, body). Supports `k: v`, `k: |` blocks, and `- ` lists."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 3)
    if end == -1:
        raise BuildError("unterminated frontmatter")
    raw, body = text[4:end], text[end + 5 :]

    data: dict = {}
    lines = raw.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.lstrip().startswith("#"):
            i += 1
            continue
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not m:
            raise BuildError(f"unparsable frontmatter line: {line!r}")
        key, value = m.group(1), m.group(2).strip()

        if value == "|":  # block scalar
            i += 1
            block: list[str] = []
            while i < len(lines) and (lines[i].startswith("  ") or not lines[i].strip()):
                block.append(lines[i][2:] if lines[i].startswith("  ") else "")
                i += 1
            data[key] = "\n".join(block).rstrip() + "\n"
            continue

        if value == "":  # possibly a list
            i += 1
            items: list[str] = []
            while i < len(lines) and re.match(r"^\s+-\s+", lines[i]):
                items.append(re.sub(r"^\s+-\s+", "", lines[i]).strip().strip("\"'"))
                i += 1
            data[key] = items
            continue

        data[key] = value.strip().strip("\"'")
        i += 1
    return data, body


def read_doc(path: Path) -> tuple[dict, str]:
    try:
        return parse_frontmatter(path.read_text(encoding="utf-8"))
    except BuildError as exc:
        raise BuildError(f"{path.relative_to(ROOT)}: {exc}") from exc


# ---------------------------------------------------------------------- lint


def scan_forbidden(path: Path, text: str, errors: list[str]) -> None:
    for pattern, label in FORBIDDEN:
        for match in pattern.finditer(text):
            hit = match.group(0)
            if any(a in match.string[max(0, match.start() - 20) : match.end() + 20] for a in ALLOWED_SUBSTRINGS):
                continue
            if hit in ALLOWED_SUBSTRINGS:
                continue
            line = text[: match.start()].count("\n") + 1
            errors.append(f"{path.relative_to(ROOT)}:{line}: {label} in a public repo: {hit!r}")


def check_shell_blocks(path: Path, text: str, errors: list[str]) -> None:
    """Catch the newline-eaten corruption seen in the source agent.md export."""
    # Narrow on purpose: these patterns only occur when newlines were eaten during an
    # export. A broad rule like \bfi[a-z]+\b matches "first" and "finally".
    suspicious = re.compile(
        r"(apt-get\s+\w+[a-z-]*sudo|sudo\s+\S+[a-z]sudo\b|\bdone[a-z]{2,}|"
        r"<server-ip>cd\b|>/dev/nullsudo|\bfi(sudo|cd|echo)\b)"
    )
    for block in re.findall(r"```(?:bash|sh)?\n(.*?)```", text, re.S):
        for match in suspicious.finditer(block):
            errors.append(
                f"{path.relative_to(ROOT)}: shell block looks newline-corrupted near {match.group(0)!r}"
            )


# --------------------------------------------------------------- collection


def load_layer(directory: Path) -> list[tuple[Path, dict, str]]:
    if not directory.is_dir():
        return []
    out = []
    for path in sorted(directory.glob("*.md")):
        fm, body = read_doc(path)
        out.append((path, fm, body.strip() + "\n"))
    return out


def slug(path: Path) -> str:
    return path.stem


# ----------------------------------------------------------------- renderers


def render_claude_core(core) -> str:
    parts = [GENERATED.format(v=VERSION), ""]
    for _path, _fm, body in core:
        parts.append(body.rstrip())
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def render_scoped_rule(fm: dict, body: str) -> str:
    paths = fm.get("paths") or []
    if not paths:
        raise BuildError("scoped rule has no `paths:` globs")
    lines = ["---", "paths:"]
    lines += [f'  - "{p}"' for p in paths]
    lines += ["---", "", GENERATED.format(v=VERSION), ""]
    return "\n".join(lines) + body.rstrip() + "\n"


def render_codex(core, scoped, skills) -> str:
    """Core inline (verbatim or hand-written digest) + soft pointers for the rest.

    Codex has no import syntax and no path scoping, so anything not inline here is
    only reachable if the model chooses to open the pointer path.
    """
    parts = [
        GENERATED.format(v=VERSION),
        "",
        "# Global engineering rules",
        "",
        "These apply to every project on this machine. Project AGENTS.md files add to them and",
        "win on conflict, except where a rule below says it cannot be overridden.",
        "",
    ]
    for _path, fm, body in core:
        if fm.get("codex") == "digest" and fm.get("digest"):
            parts.append(fm["digest"].rstrip())
        elif fm.get("codex") == "pointer":
            continue
        else:
            parts.append(body.rstrip())
        parts.append("")

    if scoped or skills:
        parts += [
            "---",
            "",
            "## Detailed rules — read the relevant file before acting",
            "",
            "These are not loaded automatically. Open the one that matches what you are about to",
            "touch. A copy also lives in the project's `.agent/rules/` where one has been set up.",
            "",
        ]
        for path, fm, _body in scoped:
            globs = " ".join((fm.get("paths") or [])[:2])
            parts.append(f"- {globs} -> {PREFIX_TOKEN}/dist/claude/rules/airules-{slug(path)}.md")
        for d in skills:
            parts.append(f"- skill `{d.name}` -> {PREFIX_TOKEN}/dist/skills/{d.name}/SKILL.md")
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def render_agents_generic(core, scoped) -> str:
    """agents.md-standard artifact for Cursor/Copilot/Zed — no byte pressure."""
    parts = [GENERATED.format(v=VERSION), "", "# Global engineering rules", ""]
    for _path, _fm, body in core:
        parts.append(body.rstrip())
        parts.append("")
    for path, fm, body in scoped:
        globs = ", ".join(fm.get("paths") or [])
        parts.append(f"<!-- applies to: {globs} -->")
        parts.append(body.rstrip())
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def render_claude_stub() -> str:
    return (
        f"{GENERATED.format(v=VERSION)}\n\n"
        "# Global rules\n\n"
        "House engineering rules load automatically from `~/.claude/rules/airules-*.md`.\n"
        "Book-derived design methodologies are installed as skills named `book-*`; house\n"
        "procedures as `idn-*`. Load at most one `book-*` skill per task.\n"
    )


