HOUSE_OVERRIDES = """## House overrides

These outrank anything above and are not from the book.

- Core rules 00-60 always win. This skill never authorises a merge, a force-push, a destructive
  command, or a "tests pass" claim you did not run.
- Never refactor or restructure code the user did not ask you to touch. If it is needed to make
  the requested change safely, say so and get a yes first.
- Test policy — when to write tests and how — belongs to the `tdd` skill, not to this one.
- Load at most one `book-*` skill per task. If a second seems relevant, name both, choose, say why
  in one line, and continue.

If you notice you have already applied guidance from another `book-*` skill in this session, say
so, name which one governs the file you are in, and stop applying the other.
"""


def book_source(spec: str) -> Path:
    """`slug` -> the mini file; `slug:full` -> the full file."""
    if spec.endswith(":full"):
        s = spec[: -len(":full")]
        return VENDOR / "books" / s / f"{s}.md"
    return VENDOR / "books" / spec / f"{spec}.mini.md"


def split_mini(text: str) -> tuple[str, str]:
    """Return (when_to_use, remaining_sections) from a vendored mini ruleset."""
    body = re.sub(r"^#\s+OBEY.*?\n", "", text, count=1).lstrip()
    m = re.search(r"^##\s+When to use\s*\n(.*?)(?=^##\s)", body, re.S | re.M)
    when = " ".join(m.group(1).split()) if m else ""
    rest = re.sub(r"^##\s+When to use\s*\n.*?(?=^##\s)", "", body, count=1, flags=re.S | re.M)
    return when, rest.strip() + "\n"


def build_book_skills(errors: list[str]) -> list[Path]:
    made: list[Path] = []
    for name, spec in BOOK_SKILLS.items():
        src = book_source(spec["body"])
        if not src.exists():
            errors.append(f"missing vendored book for {name}: {src.relative_to(ROOT)}")
            continue
        when, rest = split_mini(src.read_text(encoding="utf-8"))
        negative = "Do NOT use for unrelated work, and never load a second book-* skill in the same task."
        description = f"{when} {negative}".strip()
        if len(description) > SKILL_DESC_MAX:
            description = description[: SKILL_DESC_MAX - 1].rsplit(" ", 1)[0]

        conflicts = "\n".join(f"- **`{other}`** — {verdict}" for other, verdict in spec["conflicts"])
        out_dir = DIST / "skills" / name
        out_dir.mkdir(parents=True, exist_ok=True)

        refs = []
        for filename, ref_spec in spec["refs"].items():
            ref_src = book_source(ref_spec)
            if not ref_src.exists():
                errors.append(f"missing reference for {name}: {ref_src.relative_to(ROOT)}")
                continue
            shutil.copyfile(ref_src, out_dir / filename)
            refs.append(f"- `{filename}` — open for one entry; do not read whole.")

        doc = (
            "---\n"
            f"name: {name}\n"
            f"description: {description}\n"
            "---\n\n"
            f"# {spec['title']}\n\n"
            f"> Distilled from *{spec['attrib']}*. MIT-licensed ruleset vendored from\n"
            "> ciembor/agent-rules-books.\n\n"
            "## Conflicts\n\n"
            "Mutually exclusive with other `book-*` skills — one per task (core rule 60).\n\n"
            f"{conflicts}\n\n"
            f"{rest}\n"
            f"{HOUSE_OVERRIDES}\n"
            + ("\n## Deeper reference\n\n" + "\n".join(refs) + "\n" if refs else "")
        )
        (out_dir / "SKILL.md").write_text(doc, encoding="utf-8")
        made.append(out_dir)
    return made


# ------------------------------------------------------------------- driver


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def budget(label: str, path: Path, cap: int, errors: list[str]) -> dict:
    n = path.stat().st_size
    if n > cap:
        errors.append(f"{label}: {n} B exceeds the {cap} B budget (over by {n - cap} B)")
    return {"file": str(path.relative_to(ROOT)), "bytes": n, "budget": cap}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lint-only", action="store_true")
    ap.add_argument("--verify-vendor", action="store_true")
    args = ap.parse_args()

    errors: list[str] = []

    if args.verify_vendor:
        lock = VENDOR / "books.lock.json"
        if not lock.exists():
            print("no vendor/books.lock.json", file=sys.stderr)
            return 1
        data = json.loads(lock.read_text(encoding="utf-8"))
        for rel, want in sorted(data.get("files", {}).items()):
            p = VENDOR / "books" / rel
            if not p.exists():
                errors.append(f"vendored file missing: {rel}")
            elif sha256(p) != want:
                errors.append(f"vendored file modified: {rel}")
        for e in errors:
            print(f"ERROR {e}", file=sys.stderr)
        print("vendor verified" if not errors else f"{len(errors)} vendor error(s)")
        return 1 if errors else 0

    core = load_layer(SRC / "core")
    scoped = load_layer(SRC / "scoped")
    if not core:
        print("ERROR no src/core/*.md", file=sys.stderr)
        return 1

    for path, _fm, body in core + scoped:
        scan_forbidden(path, body, errors)
        check_shell_blocks(path, body, errors)
    for path in sorted(SRC.glob("skills/*/*.md")):
        text = path.read_text(encoding="utf-8")
        scan_forbidden(path, text, errors)
        check_shell_blocks(path, text, errors)
        fm, _ = parse_frontmatter(text)
        combined = len(str(fm.get("description", ""))) + len(str(fm.get("when_to_use", "")))
        if combined > SKILL_DESC_MAX:
            errors.append(f"{path.relative_to(ROOT)}: description+when_to_use is {combined} chars (max {SKILL_DESC_MAX})")

    if args.lint_only:
        for e in errors:
            print(f"ERROR {e}", file=sys.stderr)
        print("lint clean" if not errors else f"{len(errors)} lint error(s)")
        return 1 if errors else 0

    if DIST.exists():
        shutil.rmtree(DIST)
    (DIST / "claude" / "rules").mkdir(parents=True)
    (DIST / "codex").mkdir(parents=True)
    (DIST / "agents").mkdir(parents=True)
    (DIST / "skills").mkdir(parents=True)

    core_out = DIST / "claude" / "rules" / "airules-00-core.md"
    core_out.write_text(render_claude_core(core), encoding="utf-8")

    scoped_bytes = 0
    for path, fm, body in scoped:
        out = DIST / "claude" / "rules" / f"airules-{slug(path)}.md"
        try:
            out.write_text(render_scoped_rule(fm, body), encoding="utf-8")
        except BuildError as exc:
            errors.append(f"{path.relative_to(ROOT)}: {exc}")
            continue
        scoped_bytes += out.stat().st_size

    (DIST / "claude" / "CLAUDE.md").write_text(render_claude_stub(), encoding="utf-8")

    house_skill_dirs = sorted(d for d in (SRC / "skills").glob("*") if d.is_dir())
    for d in house_skill_dirs:
        shutil.copytree(d, DIST / "skills" / d.name)
    book_dirs = build_book_skills(errors)

    codex_out = DIST / "codex" / "AGENTS.md"
    codex_out.write_text(render_codex(core, scoped, house_skill_dirs + book_dirs), encoding="utf-8")
    (DIST / "agents" / "AGENTS.md").write_text(render_agents_generic(core, scoped), encoding="utf-8")

    budgets = [
        budget("dist/claude/rules/airules-00-core.md", core_out, BUDGET_CLAUDE_CORE, errors),
        budget("dist/codex/AGENTS.md", codex_out, BUDGET_CODEX, errors),
    ]
    if scoped_bytes > BUDGET_SCOPED_TOTAL:
        errors.append(f"scoped layer: {scoped_bytes} B exceeds the {BUDGET_SCOPED_TOTAL} B budget")

    artifacts = {
        str(p.relative_to(DIST)): {"sha256": sha256(p), "bytes": p.stat().st_size}
        for p in sorted(DIST.rglob("*"))
        if p.is_file()
    }
    (DIST / "MANIFEST.json").write_text(
        json.dumps(
            {
                "version": VERSION,
                "prefix_token": PREFIX_TOKEN,
                "budgets": budgets,
                "scoped_bytes": scoped_bytes,
                "skills": sorted(d.name for d in (DIST / "skills").glob("*") if d.is_dir()),
                "artifacts": artifacts,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    for e in errors:
        print(f"ERROR {e}", file=sys.stderr)
    if errors:
        print(f"\n{len(errors)} error(s) — dist/ written but not valid", file=sys.stderr)
        return 1

    print(f"built agent-rules {VERSION}")
    for b in budgets:
        print(f"  {b['file']}: {b['bytes']} / {b['budget']} B")
    print(f"  scoped layer: {scoped_bytes} / {BUDGET_SCOPED_TOTAL} B")
    print(f"  skills: {len(artifacts and [d for d in (DIST / 'skills').glob('*') if d.is_dir()])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
